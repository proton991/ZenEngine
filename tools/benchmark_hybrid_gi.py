"""Sequential P8 workload, grid, algorithm, queue and production-scene light measurements.

Pass the frozen top/hall glTF files generated by capture_hybrid_gi.py. Each case
uses benchmark_voxel_gi.py's transactional configuration, shader/executable hashes,
full-frame timing, CPU submission timing and committed-memory accounting. These
measurements do not establish image quality or qualify an untested device.
"""
import argparse
import json
import math
from pathlib import Path
import subprocess
import sys

from capture_hybrid_gi import CAMERAS, ROOT, fingerprint


# Baseline workload shared with profile_hybrid_gi.py; each case adds the frozen view.
BASELINE = dict(scene_lighting_override='true', light_count=0,
    environment_texture='papermill.ktx', environment_lighting='true', environment_intensity=1,
    environment_rotation_degrees=0, skybox_visible='true', voxel_resolution=64,
    voxel_gi_samples=4, voxel_gi_reference_samples=0, voxel_gi_adaptive_sampling='true',
    voxel_gi_indirect_intensity=1, voxel_gi_history_frames=32, voxel_gi_temporal='true',
    voxel_gi_filter='true', voxel_gi_specular_occlusion='true', voxel_gi_reflections='true',
    voxel_gi_bounce_source='auto', voxel_gi_shadow_enabled='true', voxel_gi_rt_shadows='true')
BASELINE.update({'dynamic_light.enabled': 'false', 'light_markers.enabled': 'false'})


def check_frozen_view(path, camera):
    document = json.loads(path.read_text())
    if document['nodes'][-1].get('matrix') != CAMERAS[camera]:
        raise ValueError(f'{path} does not contain the frozen {camera} camera')
    manifest = json.loads(path.with_suffix('.inputs.json').read_text())
    if manifest['settings']['environment_texture'] != 'papermill.ktx':
        raise ValueError(f'{path} needs the frozen Papermill capture manifest')
    for entry in manifest['source_inputs']:
        if fingerprint(Path(entry['path']))['sha256'] != entry['sha256']:
            raise ValueError(f'Stale frozen-scene dependency: {entry["path"]}')


def cases(args):
    views = {'top': args.top_scene.resolve(), 'hall': args.hall_scene.resolve()}
    for camera, path in views.items():
        check_frozen_view(path, camera)
    environment = BASELINE
    result = []
    for backend in ('compute', 'hardware'):
        for camera, scene in views.items():
            base = environment | {'default_model_path': scene.as_posix()}
            if 'baseline' in args.groups:
                result.append((f'{camera}-{backend}', backend, base, []))
            if 'grids' in args.groups:
                for resolution in (128, 256):
                    result.append((f'{camera}-{backend}-grid{resolution}', backend,
                                   base | {'voxel_resolution': resolution}, []))
            if 'algorithms' in args.groups:
                for bounce, reflections in (('cone', 'true'), ('rays', 'true'), ('cone', 'false'), ('rays', 'false')):
                    result.append((f'{camera}-{backend}-{bounce}-reflections-{reflections}', backend,
                        base | {'voxel_gi_bounce_source': bounce, 'voxel_gi_reflections': reflections},
                        ['--legacy-provider-controls']))
            if 'queues' in args.groups:
                result.append((f'{camera}-{backend}-graphics-queue', backend, base, ['--async-compute', '0']))
        if 'lighting' in args.groups:
            for count in (1, 4, 16, 32):
                lights = environment | {'default_model_path': views['hall'].as_posix(), 'light_count': count}
                for index in range(count):
                    angle = 2 * math.pi * index / count
                    lights.update({f'light.{index}.type': 'point',
                        f'light.{index}.position': f'{.65 * math.cos(angle)},-.2,{.12 * math.sin(angle)}',
                        f'light.{index}.color': '1,1,1', f'light.{index}.intensity': 20 / count,
                        f'light.{index}.range': 1000, f'light.{index}.enabled': 'true',
                        f'light.{index}.casts_shadows': 'true'})
                for moving in (False, True):
                    settings = lights | {'dynamic_light.enabled': str(moving).lower(),
                        'dynamic_light.index': count - 1, 'dynamic_light.orbit_center': '0,-.2,0',
                        'dynamic_light.orbit_radius': .12, 'dynamic_light.angular_speed_degrees': 45}
                    result.append((f'hall-{backend}-{count}-lights-{"one-moving" if moving else "static"}',
                                   backend, settings, []))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--exe', type=Path, required=True)
    parser.add_argument('--top-scene', type=Path, required=True)
    parser.add_argument('--hall-scene', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--groups', nargs='+', choices=('baseline', 'grids', 'algorithms', 'lighting', 'queues'),
                        default=['baseline'])
    parser.add_argument('--frames', type=int, default=1200)
    parser.add_argument('--warmup', type=int, default=120)
    args = parser.parse_args()
    workloads = cases(args)
    args.output.mkdir(parents=True, exist_ok=False)
    config = ROOT / 'Data/engine.cfg'
    original = config.read_bytes()
    base_config = args.output.resolve() / 'base-engine.cfg'
    base_config.write_bytes(original)
    report = dict(executable=fingerprint(args.exe.resolve()), requested_groups=args.groups,
        frozen_views={camera: fingerprint(path.resolve()) for camera, path in
                      (('top', args.top_scene), ('hall', args.hall_scene))},
        source_inputs=json.loads(args.hall_scene.with_suffix('.inputs.json').read_text())['source_inputs'],
        lighting_motion='One point light orbits; remaining lights stay static.',
        expected_cases=len(workloads), cases={}, complete=False)
    for name, backend, settings, extra in workloads:
        output = args.output / name
        command = [sys.executable, str(ROOT / 'tools/benchmark_voxel_gi.py'),
            '--executable', str(args.exe.resolve()), '--output', str(output.resolve()),
            '--config', str(base_config), '--backend', backend, '--profile',
            '--frames', str(args.frames), '--warmup', str(args.warmup), *extra]
        for key, value in settings.items():
            command += ['--set', f'{key}={value}']
        with (args.output / f'{name}.log').open('w') as log:
            process = subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
        if config.read_bytes() != original:
            raise RuntimeError('Configuration was not restored; preserving the external changes')
        measured = json.loads((output / 'summary.json').read_text()) if process.returncode == 0 else None
        report['cases'][name] = dict(settings=settings, summary=measured, exit_code=process.returncode,
                                    target_met=measured is not None and measured['fps'] >= 60)
        report['complete'] = len(report['cases']) == len(workloads)
        (args.output / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
        if measured is not None:
            print(name, f'{measured["fps"]:.2f} FPS', measured['gpu_frame_ms']['measured'], flush=True)
        else:
            print(name, f'FAILED ({process.returncode}); see {name}.log', flush=True)
    if any(case['exit_code'] != 0 for case in report['cases'].values()):
        raise SystemExit(1)


if __name__ == '__main__':
    main()
