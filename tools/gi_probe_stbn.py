"""Generate the optional probe sampler's 16 × 16 × 64 spatiotemporal blue-noise ordering.

Uses the scalar void-and-cluster energy described by Wolfe et al. in
https://research.nvidia.com/publication/2022-07_spatiotemporal-blue-noise-masks .
Each tile's 64 ranks form a permutation, so a stationary probe visits every Sobol point.
"""
import argparse
from pathlib import Path

import numpy as np


def generate():
    side, frames = 16, 64
    shape = (frames, side, side)
    space = np.minimum(np.arange(side), side - np.arange(side))
    time = np.minimum(np.arange(frames), frames - np.arange(frames))
    spatial = np.exp(-(space[:, None] ** 2 + space[None, :] ** 2) / (2 * 1.9 ** 2))
    temporal = np.exp(-time ** 2 / (2 * 1.9 ** 2))
    temporal[0] = 0  # The spatial slice already includes the center.
    spatial = np.stack([np.roll(spatial, (y, x), axis=(0, 1)) for y, x in np.ndindex(side, side)])
    temporal = np.stack([np.roll(temporal, t) for t in range(frames)])
    occupied = np.zeros(shape, dtype=bool)
    energy = np.zeros(shape)

    def set_point(index, active):
        t, y, x = np.unravel_index(index, shape)
        sign = 1 if active else -1
        occupied[t, y, x] = active
        energy[t] += sign * spatial[y * side + x]
        energy[:, y, x] += sign * temporal[t]

    def densest():
        return np.argmax(np.where(occupied, energy, -np.inf))

    def emptiest():
        return np.argmin(np.where(occupied, np.inf, energy))

    count = occupied.size // 10
    for index in np.random.default_rng(271828).choice(occupied.size, count, replace=False):
        set_point(index, True)
    while True:
        old = densest()
        set_point(old, False)
        new = emptiest()
        set_point(new, True)
        if old == new:
            break
    initial, initial_energy = occupied.copy(), energy.copy()
    ranks = np.empty(shape, dtype=np.uint16)
    for rank in reversed(range(count)):
        index = densest()
        ranks.flat[index] = rank
        set_point(index, False)
    occupied[:], energy[:] = initial, initial_energy
    for rank in range(count, occupied.size // 2):
        index = emptiest()
        ranks.flat[index] = rank
        set_point(index, True)
    occupied[:] = ~occupied
    energy[:] = spatial[0].sum() + temporal[0].sum() - energy
    for rank in range(occupied.size // 2, occupied.size):
        index = densest()
        ranks.flat[index] = rank
        set_point(index, False)
    return np.argsort(np.argsort(ranks, axis=0), axis=0).astype(np.uint8)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    ranks = generate()
    words = np.frombuffer(ranks.tobytes(), dtype='<u4')
    lines = ['// Generated by tools/gi_probe_stbn.py', '// clang-format off',
             'static constexpr uint32_t kProbeBlueNoise[] = {']
    for offset in range(0, len(words), 8):
        lines.append('    ' + ', '.join(f'0x{word:08x}u' for word in words[offset:offset + 8]) + ',')
    # The repository is LF; write_text would translate newlines to CRLF on Windows.
    args.output.write_text('\n'.join(lines + ['};', '// clang-format on', '']), encoding='ascii', newline='\n')


if __name__ == '__main__':
    main()
